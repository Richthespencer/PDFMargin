export type Lang = 'zh' | 'zh-TW' | 'en' | 'ja' | 'ko' | 'es' | 'fr' | 'de';

export const LANG_OPTIONS: ReadonlyArray<{ code: Lang; label: string; htmlLang: string }> = [
  { code: 'zh', label: '简体中文', htmlLang: 'zh-CN' },
  { code: 'zh-TW', label: '繁體中文', htmlLang: 'zh-TW' },
  { code: 'en', label: 'English', htmlLang: 'en' },
  { code: 'ja', label: '日本語', htmlLang: 'ja' },
  { code: 'ko', label: '한국어', htmlLang: 'ko' },
  { code: 'es', label: 'Español', htmlLang: 'es' },
  { code: 'fr', label: 'Français', htmlLang: 'fr' },
  { code: 'de', label: 'Deutsch', htmlLang: 'de' },
];

const SUPPORTED_SET = new Set<string>(LANG_OPTIONS.map((item) => item.code));

export function isSupportedLang(value: string | null | undefined): value is Lang {
  return Boolean(value && SUPPORTED_SET.has(value));
}

export function detectBrowserLang(): Lang {
  const candidates =
    typeof navigator !== 'undefined'
      ? [
          ...(Array.isArray(navigator.languages) ? navigator.languages : []),
          navigator.language || (navigator as { userLanguage?: string }).userLanguage || '',
        ]
      : [];

  for (const raw of candidates) {
    const tag = raw.toLowerCase();
    if (!tag) continue;
    if (tag.startsWith('zh-tw') || tag.startsWith('zh-hk') || tag.startsWith('zh-mo') || tag.includes('hant')) {
      return 'zh-TW';
    }
    if (tag.startsWith('zh')) return 'zh';
    if (tag.startsWith('ja')) return 'ja';
    if (tag.startsWith('ko')) return 'ko';
    if (tag.startsWith('es')) return 'es';
    if (tag.startsWith('fr')) return 'fr';
    if (tag.startsWith('de')) return 'de';
    if (tag.startsWith('en')) return 'en';
  }
  return 'en';
}

export function loadPersistedLang(): Lang {
  try {
    const saved = localStorage.getItem('pdfmargin-lang');
    if (isSupportedLang(saved)) {
      return saved;
    }
  } catch {}
  return detectBrowserLang();
}

export function translateStaticStatus<T extends Record<string, unknown>>(
  copyMap: Record<Lang, T>,
  prevLang: Lang,
  nextLang: Lang,
  currentStatus: string,
): string {
  if (prevLang === nextLang) return currentStatus;
  const prevDict = copyMap[prevLang];
  const nextDict = copyMap[nextLang];
  for (const key of Object.keys(prevDict)) {
    const prevVal = prevDict[key];
    const nextVal = nextDict[key];
    if (typeof prevVal === 'string' && typeof nextVal === 'string' && prevVal === currentStatus) {
      return nextVal;
    }
  }
  for (const langKey of Object.keys(copyMap) as Lang[]) {
    const dict = copyMap[langKey];
    for (const key of Object.keys(dict)) {
      const val = dict[key];
      const nextVal = nextDict[key];
      if (typeof val === 'string' && typeof nextVal === 'string' && val === currentStatus) {
        return nextVal;
      }
    }
  }
  return currentStatus;
}

